// Generates src/content/docs/reference/tools.md from the server's own tool definitions, so the
// site's tool list can't drift from the code. Needs the server built first (npm run build in the
// repo root → dist/). Run: node scripts/gen-tools.mjs (the site's prebuild does it).

import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const defs = await import(pathToFileURL(resolve(here, '../../dist/handlers/tool.definitions.js')).href);
const { TOOL_DEFINITIONS, TOOL_CATEGORIES } = defs.default ?? defs;

const byName = new Map(TOOL_DEFINITIONS.map((t) => [t.name, t]));
// First sentence (or ~220 characters) of a description; table-safe.
const short = (d = '') => {
  // The Kind column says read-only already; < would start an HTML tag in Markdown.
  const s = String(d).replace(/\s+/g, ' ').trim().replace(/^READ-ONLY[^.]*\.\s*/i, '');
  const cut = s.search(/(?<=[a-z)\]"'])(?<!\be\.g)(?<!\bi\.e)(?<!\bvs)(?<!\betc)\.\s/);
  const one = cut > 20 && cut < 240 ? s.slice(0, cut + 1) : s.length > 220 ? `${s.slice(0, 217)}…` : s;
  return one.replace(/\|/g, '\\|').replace(/</g, '&lt;');
};
const flags = (t) => {
  const a = t.annotations ?? {};
  return a.readOnlyHint ? 'read-only' : a.destructiveHint ? 'destructive' : 'writes';
};

const seen = new Set();
const sections = [];
for (const [key, cat] of Object.entries(TOOL_CATEGORIES)) {
  const tools = cat.tools.map((n) => byName.get(n)).filter(Boolean);
  if (!tools.length) continue;
  tools.forEach((t) => seen.add(t.name));
  const title = key.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
  sections.push(`## ${title}\n\n${cat.description}\n\n| Tool | Kind | What it does |\n|---|---|---|\n${tools.map((t) => `| \`${t.name}\` | ${flags(t)} | ${short(t.description)} |`).join('\n')}\n`);
}
const rest = TOOL_DEFINITIONS.filter((t) => !seen.has(t.name));
if (rest.length) sections.push(`## Platform & meta\n\nTools for clients and operators: discovery, the mirror, backpressure, requests.\n\n| Tool | Kind | What it does |\n|---|---|---|\n${rest.map((t) => `| \`${t.name}\` | ${flags(t)} | ${short(t.description)} |`).join('\n')}\n`);

const out = `---
title: Tools Reference
description: Every tool the PSArelay exposes, by category — generated from the server's own definitions.
---

<!-- Generated by website/scripts/gen-tools.mjs from src/handlers/tool.definitions.ts — do not edit by hand. -->

The server exposes **${TOOL_DEFINITIONS.length} tools**. *Kind* says whether a tool only reads, writes, or can
delete; write tools that change many records or money default to a dry run and need an explicit confirmation.
The full input schema of each tool is in [\`src/handlers/tool.definitions.ts\`](https://github.com/GDSTechnology/psarelay/blob/main/src/handlers/tool.definitions.ts).

${sections.join('\n')}`;
writeFileSync(resolve(here, '../src/content/docs/reference/tools.md'), out);
console.log(`tools.md: ${TOOL_DEFINITIONS.length} tools in ${sections.length} sections`);
